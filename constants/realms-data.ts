export const getRealmById = (id: number): Realm | undefined => {
  return REALMS_DATA.find((realm) => realm.id === id);
};

export const getRealmsByGate = (gate: number): Realm[] => {
  return REALMS_DATA.filter((realm) => realm.gate === gate);
};

export const getRealmsByElement = (element: string): Realm[] => {
  return REALMS_DATA.filter((realm) => realm.element === element);
};

export const getRealmsByZodiac = (zodiac: string): Realm[] => {
  return REALMS_DATA.filter((realm) => realm.zodiac === zodiac);
};
